# Merge into data_females
import re
def norm(s):
    s = re.sub(r'[\u064B-\u0652]', '', s)
    s = re.sub(r'[إأآا]', 'ا', s)
    s = re.sub(r'ة', 'ه', s)
    s = re.sub(r'ى', 'ي', s)
    return s.strip()

seen = {norm(item[0]): item for item in data_females.FEMALE_NAMES}
added = 0
for item in EXTRA_FEMALES:
    n = norm(item[0])
    if n not in seen:
        seen[n] = item
        data_females.FEMALE_NAMES.append(item)
        added += 1

print(f"Added {added} extra females.")
print(f"Total female names now: {len(data_females.FEMALE_NAMES)}")

