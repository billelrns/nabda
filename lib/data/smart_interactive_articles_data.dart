/// قسم فرعي داخل المقال
class ArticleSection {
  final String title;
  final String content;
  final List<String> bulletPoints;
  final String? calloutTip; // نصيحة ذهبية
  final String? calloutWarning; // تنبيه طبي هام

  const ArticleSection({
    required this.title,
    required this.content,
    this.bulletPoints = const [],
    this.calloutTip,
    this.calloutWarning,
  });
}

/// سؤال وجواب شائع
class ArticleFAQ {
  final String question;
  final String answer;
  const ArticleFAQ({required this.question, required this.answer});
}

/// نموذج المقال التفاعلي الذكي
class SmartArticle {
  final String id;
  final String categoryId;
  final String categoryName;
  final String title;
  final String readTime;
  final String author;
  final String badge;
  final String summary;
  final String iconEmoji;
  final Color themeColor;
  final List<ArticleSection> sections;
  final List<ArticleFAQ> faqs;
  final ArticleToolType? toolType;
  final String? toolTitle;
  final String? toolSubtitle;

  const SmartArticle({
    required this.id,
    required this.categoryId,
    required this.categoryName,
    required this.title,
    required this.readTime,
    this.author = 'فريق نبضة الطبي · تدقيق استشاري',
    this.badge = 'مقال موثق',
    required this.summary,
    required this.iconEmoji,
    required this.themeColor,
    required this.sections,
    this.faqs = const [],
    this.toolType,
    this.toolTitle,
    this.toolSubtitle,
  });
}

