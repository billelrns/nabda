/// مرجع فتوى من أحد الموقعين المعتمدين
class FatwaRef {
  final String site; // 'إسلام ويب' أو 'الإسلام سؤال وجواب'
  final String title;
  final String url;
  const FatwaRef(this.site, this.title, this.url);
}

/// دعاء واحد مع توثيقه
class Dua {
  final String text;

  /// «آل عمران: 38» أو «رواه البخاري (141) ومسلم (1434)»
  final String source;

  /// «قرآن كريم» • «متفق عليه» • «صحيح» • «حسن» • «ضعيف الإسناد»
  final String grade;

  /// سياق الدعاء أو فائدته — بلا وعد بنتيجة
  final String note;

  /// فتوى مرجعية من إسلام ويب أو الإسلام سؤال وجواب
  final FatwaRef? ref;

  const Dua({
    required this.text,
    required this.source,
    required this.grade,
    this.note = '',
    this.ref,
  });

  bool get isQuran => grade == 'قرآن كريم';
}

