  /// يُحوّل النصّ إن كان المستخدم أباً، وإلا يُعيده كما هو.
  static String t(String s) {
    if (!isFather) return s;

    // 1) مطابقة العبارة الكاملة
    final exact = _phrases[s.trim()];
    if (exact != null) return exact;

    // 2) استبدال العبارات الواردة داخل نصّ أطول
    var out = s;
    _phrases.forEach((f, m) {
      if (out.contains(f)) out = out.replaceAll(f, m);
    });

    return out;
  }

  /// نسخة تُطبّق قاعدة اللاحقة أيضاً — للأزرار والعناوين القصيرة
  /// حيث يكون النصّ فعل أمر مفرد («تصفحي»، «أضيفي»).
  static String verb(String s) {
    if (!isFather) return s;
    final exact = t(s);
    if (exact != s) return exact;

    final words = s.split(' ');
    for (var i = 0; i < words.length; i++) {
      final w = words[i];
      if (w.length > 3 && w.endsWith('ي') && !_protected.contains(w)) {
        words[i] = w.substring(0, w.length - 1);
      }
    }
    return words.join(' ');
  }

  /// للنصوص التي تذكر «زوجك/زوجتك» حسب الدور
  static String spouse() => isFather ? 'زوجتك' : 'زوجك';

  /// ضمير الإشارة للطرف الآخر في الجمل
  static String spouseDid(String verbPast) =>
      '${spouse()} $verbPast';
